# Builds supabase/functions/_shared/help-kb.ts from the help articles in
# src/pages/help/*.tsx plus scripts/help-current.md (current facts that take
# priority). Run after editing either:  python3 scripts/build-help-kb.py
import re, json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
routes = {
  "AccurateQuotes": "/help/accurate-quotes", "Clients": "/help/clients", "CommonIssues": "/help/common-issues",
  "Contact": "/help/contact", "DemoMode": "/help/demo-mode", "InventoryPricing": "/help/inventory-pricing",
  "QuoteTemplates": "/help/quote-templates", "Scheduling": "/help/scheduling", "TaxPricing": "/help/tax-pricing",
  "Templates": "/help/templates", "Troubleshooting": "/help/troubleshooting",
}
def text(src):
    t = re.sub(r"\{/\*.*?\*/\}", "", src, flags=re.S)
    t = t[t.find("return"):]
    t = re.sub(r"(className|to|href|variant|size|key|onClick)=\{?\"?[^\"}]*\"?\}?", " ", t)
    t = re.sub(r"<[^>]+>", " ", t)
    t = re.sub(r"[{}()]|=>|\breturn\b", " ", t)
    t = t.replace("&lt;", "<").replace("&gt;", ">").replace("&amp;", "&").replace("&apos;", "'")
    return re.sub(r"\s+", " ", t).replace("Back to Help", "").strip()
articles = []
for name, path in routes.items():
    f = root / "src/pages/help" / f"{name}.tsx"
    if f.exists():
        articles.append(f"## Article: {path}\n{text(f.read_text())}")
current = (root / "scripts/help-current.md").read_text()
kb = current + "\n\n# OLDER HELP ARTICLES (where these disagree with CURRENT FACTS above, the current facts are right)\n\n" + "\n\n".join(articles)
out = root / "supabase/functions/_shared/help-kb.ts"
out.write_text("// Generated by scripts/build-help-kb.py — edit scripts/help-current.md or the help pages, then rerun.\n"
               f"export const HELP_KB = {json.dumps(kb)};\n")
print(f"wrote {out.relative_to(root)}: {len(kb)} chars")
